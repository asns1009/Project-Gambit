target_cities AS (SELECT DISTINCT order_city_name FROM base WHERE store_address_id IN (SELECT x FROM target)),
zone_map AS (
  SELECT b.zone_name,
    LOGICAL_OR(b.store_address_id IN (SELECT x FROM item7)) AS has_item7,
    LOGICAL_OR(b.store_address_id IN (SELECT x FROM target) AND b.store_address_id NOT IN (SELECT x FROM item7)) AS has_other,
