SELECT zc.cohort, DATE_TRUNC(s.p_report_date, WEEK(MONDAY)) AS week_start,
  CASE WHEN s.p_report_date <= '2026-11-01' THEN 'pre' ELSE 'post' END AS period,
  COUNT(DISTINCT s.zone_name) AS zones,
  SUM(s.total_sessions) AS sessions,
  SUM(s.sessions_impacted_by_shrinking) AS shrink_sessions,
  SUM(s.sessions_impacted_by_closure) AS closure_sessions
FROM `fulfillment-dwh-production.curated_data_shared_glovo.sessions_saturation_kpis__main_zone_day` s
JOIN zone_cohort zc ON zc.zone_name = s.zone_name
WHERE s.p_report_date BETWEEN '2026-10-05' AND '2026-11-21' AND zc.cohort IS NOT NULL
GROUP BY 1,2,3
ORDER BY 1,2,3;
