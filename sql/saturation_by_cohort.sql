  SELECT zone_name,
    CASE WHEN has_item7 AND has_other THEN 'Mixed'
         WHEN has_item7 THEN 'Item 7 Go'
         WHEN has_other THEN 'Other Experiment'
         WHEN in_target_city THEN 'Normal' END AS cohort
